import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';

test('backlink evidence → destination prerequisite → verified publisher link', async ({ page, context, request }) => {
  test.skip(!process.env.BACKLINKS_TEST_MANIFEST, 'Requires the isolated local backlink test API.');
  test.setTimeout(90_000);
  const fixture = JSON.parse(readFileSync(process.env.BACKLINKS_TEST_MANIFEST!, 'utf8')) as {
    apiBase: string; organizationId: string; projectId: string; token: string; csrfToken: string; ownSource: string; competitorSource: string; targetUrl: string;
  };
  const crashes: string[] = [];
  page.on('pageerror', (error) => crashes.push(error.message));
  page.on('console', (message) => { if (/Encountered two children|hydration failed/i.test(message.text())) crashes.push(message.text()); });
  expect((await request.post(`${fixture.apiBase}/__test__/reset`, { headers: { authorization: `Bearer ${fixture.token}` } })).ok()).toBeTruthy();
  await context.addCookies([
    { name: 'access_token', value: fixture.token, url: fixture.apiBase, httpOnly: true, sameSite: 'Lax' },
    { name: 'csrf_token', value: fixture.csrfToken, url: fixture.apiBase, sameSite: 'Lax' },
  ]);
  await page.addInitScript((data) => {
    localStorage.setItem('growthx.session', '1');
    localStorage.setItem('growthx.org', data.organizationId);
    localStorage.setItem('growthx.project', data.projectId);
  }, fixture);
  await page.goto('/backlinks');
  await expect(page.getByRole('heading', { name: 'Backlink intelligence', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Manage sources', exact: true }).click();
  await page.getByLabel('One source URL per line').fill(`${fixture.ownSource}\n${fixture.competitorSource}`);
  await page.getByRole('button', { name: 'Save candidates' }).click();
  await expect(page.getByRole('status')).toContainText('Saved as candidates');
  await page.getByRole('button', { name: 'Verify next 25 sources' }).click();
  await expect(page.getByText('READ', { exact: true })).toHaveCount(2, { timeout: 30_000 });
  await page.getByRole('button', { name: 'Observed competitor sources', exact: true }).click();
  await page.getByLabel('Your business page URL').fill(fixture.targetUrl);
  await page.getByRole('checkbox', { name: 'I reviewed this source' }).check();
  await page.getByRole('button', { name: 'Check readiness and save plan' }).click();
  await expect(page.getByText('Plan saved with a destination prerequisite.', { exact: false })).toBeVisible();
  await page.getByRole('button', { name: 'Next actions', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Prepare your destination before pursuing this link' })).toBeVisible();
  const fixed = await request.post(`${fixture.apiBase}/__test__/audit-fixed`, { headers: { authorization: `Bearer ${fixture.token}` } });
  expect(fixed.ok()).toBeTruthy();
  await page.getByRole('button', { name: 'Recheck latest audits' }).click();
  await expect(page.getByRole('heading', { name: 'Review a relevant publisher for your business page' })).toBeVisible();
  const published = await request.post(`${fixture.apiBase}/__test__/publisher-link`, { headers: { authorization: `Bearer ${fixture.token}` } });
  expect(published.ok()).toBeTruthy();
  await page.getByRole('button', { name: 'Verify source again' }).click();
  await expect(page.getByText('No verified link actions yet')).toBeVisible({ timeout: 30_000 });
  await page.getByRole('button', { name: 'Source evidence', exact: true }).click();
  const source = page.getByRole('row').filter({ hasText: fixture.competitorSource });
  await source.locator('summary').click();
  await expect(source.getByText('VERIFIED', { exact: true })).toHaveCount(2);
  await source.getByRole('button', { name: 'History' }).click();
  await expect(page.getByRole('heading', { name: 'Verification history' })).toBeVisible();
  await expect(page.getByText('Evidence SHA-256:', { exact: false }).first()).toBeVisible();
  await page.getByRole('button', { name: 'Profile & reports', exact: true }).click();
  await expect(page.getByText('Follow and qualification profile', { exact: true })).toBeVisible();
  await page.getByLabel('Backlink trend window').selectOption('7');
  await page.getByRole('button', { name: 'Referring domains', exact: true }).click();
  await expect(page.getByRole('columnheader', { name: 'Source pages', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Anchors', exact: true }).click();
  await expect(page.getByText('Anchor profile', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Top linked pages', exact: true }).click();
  await expect(page.getByRole('columnheader', { name: 'Destination readiness', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Link intersect', exact: true }).click();
  await page.getByLabel('Link intersection mode').selectOption('shared');
  await expect(page.getByText('Competitor link intersection', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'New / lost / changed', exact: true }).click();
  await expect(page.getByText('FOUND', { exact: true }).first()).toBeVisible();
  await page.getByRole('button', { name: 'Backlinks', exact: true }).click();
  await expect(page.getByText('Backlink explorer', { exact: true })).toBeVisible();
  await page.getByLabel('Search backlink source, destination or anchor').fill('no-such-backlink-fixture');
  await page.getByRole('button', { name: 'Apply search', exact: true }).click();
  await expect(page.getByText('No backlinks match these filters', { exact: true })).toBeVisible();
  await page.getByLabel('Search backlink source, destination or anchor').fill('');
  await page.getByRole('button', { name: 'Apply search', exact: true }).click();
  const downloaded = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Export filtered CSV', exact: true }).click();
  expect((await downloaded).suggestedFilename()).toMatch(/\.csv$/);
  await expect(page.getByRole('status').filter({ hasText: 'Exported' })).toContainText('Exported 2 of 2 matching rows');
  expect((await request.post(`${fixture.apiBase}/__test__/prepare-discovery`,{headers:{authorization:`Bearer ${fixture.token}`}})).ok()).toBeTruthy();
  await page.getByRole('button',{name:'Discover backlinks',exact:true}).click();
  await expect(page.getByRole('status').filter({hasText:'Discovery started'})).toBeVisible();
  await expect.poll(async()=>{
    const response=await request.get(`${fixture.apiBase}/api/projects/${fixture.projectId}/backlinks/discovery`,{headers:{authorization:`Bearer ${fixture.token}`}});
    const status=await response.json();return status.run?.verified??0;
  },{timeout:30000}).toBe(1);
  await page.getByRole('button',{name:'Discovery running…',exact:true}).waitFor({state:'hidden'});
  await expect(page.getByText('Discovery finished; live verification continues automatically',{exact:true})).toBeVisible();
  await expect(page.getByTestId('discovery-verified')).toHaveText('1');
  await page.getByRole('button', { name: 'Overview', exact: true }).click();
  await page.getByRole('button', { name: 'Day', exact: true }).click();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: 'test-results/backlinks-workflow-desktop.png', fullPage: true });
  await page.getByRole('button', { name: 'Night', exact: true }).click();
  await page.screenshot({ path: 'test-results/backlinks-workflow-dark.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.locator('main')).toHaveCSS('margin-left', '0px');
  await expect.poll(() => page.locator('aside').evaluate((element) => element.getBoundingClientRect().right)).toBeLessThanOrEqual(1);
  await page.screenshot({ path: 'test-results/backlinks-workflow-mobile.png' });
  expect(crashes).toEqual([]);
});
