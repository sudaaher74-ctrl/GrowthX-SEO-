import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {mkdirSync,readFileSync,writeFileSync,cpSync,readdirSync} from 'node:fs';
import {resolve,relative,join} from 'node:path';
const root=resolve(import.meta.dirname,'..');
const [baseCommit,outputArg]=process.argv.slice(2);
if(!/^[a-f0-9]{40}$/.test(baseCommit??'') || !outputArg)throw Error('Usage: node scripts/build-code-release.mjs BASE_COMMIT OUTPUT_DIRECTORY');
const git=(...args)=>execFileSync('git',args,{cwd:root,encoding:'utf8'}).trim();
if(git('status','--porcelain','--untracked-files=no'))throw Error('Commit source changes before building a release.');
const commit=git('rev-parse','HEAD');
const dependencies=['growthx-ai-crawler/package.json','growthx-ai-crawler/package-lock.json','growthx-ai-crawler/prisma','growthx-ai-crawler/Dockerfile','growthx-ai-crawler/docker-entrypoint.sh'];
if(git('diff','--name-only',baseCommit,commit,'--',...dependencies))throw Error('Runtime dependencies or database schema changed; use the full Docker build.');
const output=resolve(outputArg);
if(output===root || !relative(root,output).startsWith('..'))throw Error('Store release artifacts outside the Git checkout.');
mkdirSync(output,{recursive:false});
execFileSync(process.platform==='win32'?'cmd.exe':'npm',process.platform==='win32'?['/d','/s','/c','npm run build']:['run','build'],{cwd:join(root,'growthx-ai-crawler'),stdio:'inherit'});
cpSync(join(root,'growthx-ai-crawler/dist'),join(output,'dist'),{recursive:true});
cpSync(join(root,'growthx-ai-crawler/Dockerfile.code-release'),join(output,'Dockerfile'));
const files={};function hash(dir){for(const item of readdirSync(dir,{withFileTypes:true})){const path=join(dir,item.name);if(item.isDirectory())hash(path);else files[relative(output,path).replaceAll('\\','/')]=createHash('sha256').update(readFileSync(path)).digest('hex');}}hash(join(output,'dist'));
writeFileSync(join(output,'revision.json'),JSON.stringify({commit,baseCommit,sourceTree:git('rev-parse',commit+':growthx-ai-crawler'),files},null,2));
console.log('Built committed code release '+commit);
